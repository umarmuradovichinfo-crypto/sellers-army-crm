import { api } from '../lib/apiClient'

// O'z telefon stansiyamiz: «Настройка АТС» (modullar, qora ro'yxat, musiqa, chiquvchi qoidalar)
export const pbxService = {
  modules: (type) => api.get(`/pbx/modules${type ? `?type=${type}` : ''}`),
  nextNumber: (type) => api.get(`/pbx/modules/next-number?type=${type}`),
  create: (body) => api.post('/pbx/modules', body),
  update: (id, body) => api.put(`/pbx/modules/${id}`, body),
  remove: (id) => api.delete(`/pbx/modules/${id}`),
  validate: () => api.get('/pbx/flow/validate'),
  asteriskApply: () => api.post('/pbx/asterisk/apply', {}),
  asterisk: () => api.get('/pbx/asterisk/preview'),
  deviceConfig: (body) => api.post('/pbx/configurator', body),
  audioList: () => api.get('/pbx/audio'),
  audioAdd: (body) => api.post('/pbx/audio', body),
  audioRemove: (id) => api.delete(`/pbx/audio/${id}`),
  audioBlob: (id) => api.getBlob(`/pbx/audio/${id}/file`),
  autorecall: () => api.get('/pbx/autorecall'),
  saveAutorecall: (body) => api.put('/pbx/autorecall', body),
  recording: () => api.get('/pbx/recording'),
  saveRecording: (body) => api.put('/pbx/recording', body),
  callback: () => api.get('/pbx/callback'),
  saveCallback: (body) => api.put('/pbx/callback', body),
  blacklist: () => api.get('/pbx/blacklist'),
  blacklistAdd: (number, note) => api.post('/pbx/blacklist', { number, note }),
  blacklistRemove: (id) => api.delete(`/pbx/blacklist/${id}`),
  music: () => api.get('/pbx/music'),
  saveMusic: (body) => api.put('/pbx/music', body),
  outgoing: () => api.get('/pbx/outgoing'),
  saveOutgoing: (rules) => api.put('/pbx/outgoing', { rules }),
  // ovoz sintezi (matn → audio kutubxona)
  ttsVoices: () => api.get('/pbx/tts/voices'),
  ttsSettings: (provider) => api.put('/pbx/tts/settings', { provider }),
  tts: (body) => api.post('/pbx/tts', body),
  // sifat bahosi
  quality: () => api.get('/pbx/quality'),
  saveQuality: (body) => api.put('/pbx/quality', body),
  // avtoinformator
  informerSettings: () => api.get('/pbx/informer/settings'),
  saveInformerSettings: (body) => api.put('/pbx/informer/settings', body),
  informers: () => api.get('/pbx/informer'),
  informer: (id, state) => api.get(`/pbx/informer/${id}${state ? `?state=${state}` : ''}`),
  informerCreate: (body) => api.post('/pbx/informer', body),
  informerUpdate: (id, body) => api.put(`/pbx/informer/${id}`, body),
  informerRemove: (id) => api.delete(`/pbx/informer/${id}`),
  informerNumbers: (id, text) => api.post(`/pbx/informer/${id}/numbers`, { text }),
  informerAction: (id, action) => api.post(`/pbx/informer/${id}/${action}`, {}),
  // «ИИ-менеджер»: qo'ng'iroq yozuvi → matn → AI xulosa
  ai: () => api.get('/pbx/ai'),
  saveAi: (body) => api.put('/pbx/ai', body),
  aiTick: () => api.post('/pbx/ai/tick', {}),
  aiCalls: (params = {}) => api.get(`/pbx/ai/calls?${new URLSearchParams(Object.entries(params).filter(([, v]) => v !== '' && v != null))}`),
  aiCall: (id) => api.get(`/pbx/ai/calls/${encodeURIComponent(id)}`),
  aiRun: (id, body) => api.post(`/pbx/ai/calls/${encodeURIComponent(id)}/run`, body || {}),
}
